#pragma once
////////////////////////////////////////////////////////////////////////////////////////////////////
/// @file text parsing helpers shared by the assembly and memory file readers.
////////////////////////////////////////////////////////////////////////////////////////////////////

#include <cstdint>
#include <string>
#include <vector>

namespace Simulator
{
////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief a list of human readable error messages. Empty means success.
////////////////////////////////////////////////////////////////////////////////////////////////////
using Errors = std::vector<std::string>;

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief trim the whitespace from the start and ending of a string.
////////////////////////////////////////////////////////////////////////////////////////////////////
std::string trim(const std::string &str);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief remove a trailing '#' or ';' comment from a line.
////////////////////////////////////////////////////////////////////////////////////////////////////
std::string stripComment(const std::string &str);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief turn every character of a string uppercase.
////////////////////////////////////////////////////////////////////////////////////////////////////
std::string toUpper(std::string str);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief split a line into tokens, using commas and whitespace as delimiters.
////////////////////////////////////////////////////////////////////////////////////////////////////
std::vector<std::string> tokenize(const std::string &line);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief parse an optionally signed integer.
/// @param str: the text to parse.
/// @param base: 10 for decimal, 16 for hex (the 0x prefix is optional), or 0 for decimal with an
///              optional 0x prefix.
/// @param result: where the parsed value is stored.
/// @return true if the whole string was a number that fits in 63 bits, otherwise false.
////////////////////////////////////////////////////////////////////////////////////////////////////
bool parseInteger(const std::string &str, int base, std::int64_t &result);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief read every line of a file.
/// @param path: the file to read.
/// @param lines: filled with the lines of the file, in order.
/// @return false if the file could not be opened.
////////////////////////////////////////////////////////////////////////////////////////////////////
bool readLines(const std::string &path, std::vector<std::string> &lines);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief build a "path:line: error: message" string.
////////////////////////////////////////////////////////////////////////////////////////////////////
std::string formatError(const std::string &path, std::size_t line, const std::string &message);

} // namespace Simulator
